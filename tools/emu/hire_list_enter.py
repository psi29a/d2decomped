"""The hire window's list box and a key: FUN_004bebc0 (thiscall, the event).

    uv run python hire_list_enter.py [--exe PATH] > ../../tests/hire_list_enter_cases.inc

D2Win's ListBoxImplementation with the hire window's callback (0x4b3660,
hooked and recorded), its draw count +0x180772 (FUN_004bee90 adds one a
draw) and selected row +0x180738; the event's key at +8. FUN_00420290
hooked. Every case of draws x selected x key: whether the callback ran and
what FUN_004bebc0 returned.
"""
import sys

import emu

CALLBACK, DRAWS, SELECTED, SIZE = 0x18074A, 0x180772, 0x180738, 0x180800


def main():
    args = sys.argv[1:]
    exe = args[1] if args[:1] == ["--exe"] else None
    e = emu.Emu(exe=exe)
    box = e.alloc(SIZE)
    event = e.alloc(0x40)
    called = []
    e.hook(0x4B3660, lambda e: called.append(1) or 0, 0)
    e.hook(0x420290, lambda e: 0, 1)
    e.w32(box + CALLBACK, 0x4B3660)
    print("// Stock game.exe 1.14d, FUN_004bebc0; generated by tools/emu/hire_list_enter.py.")
    print("// { draws, selected, key, the callback ran, returned }")
    for draws in (0, 1, 2, 3, 0xFFFFFFFF):
        for selected in (-1, 0, 1, 6, 127, -2):
            for key in (0xD, 0x1B, 0x20, 0xA, 0x10D):
                e.w32(box + DRAWS, draws)
                e.w32(box + SELECTED, selected & 0xFFFFFFFF)
                e.mu.mem_write(event, bytes(0x40))
                e.w32(event + 8, key)
                called.clear()
                ret = e.call(0x4BEBC0, event, ecx=box)
                print(f"    {{ {draws:#x}u, {selected}, {key:#x}, {len(called)}, {ret} }},")


if __name__ == "__main__":
    main()
