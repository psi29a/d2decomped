"""game.exe 1.14d's charge-up sounds (cltprgfunc 12 / 13), run by its own code.

    uv run python charge_up_sound.py gen 300 1 > cases.tsv
    uv run python charge_up_sound.py game cases.tsv > g.txt
    ../../build/tests/test_charge_up_sound cases.tsv | diff g.txt -
    uv run python charge_up_sound.py inc g.txt > ../../tests/charge_up_sound_cases.inc

FUN_004c6ac0 runs a progressive skill's cltprgfunc for the charge count as
a charge lands. Tiger Strike's 12 (FUN_004f30a0) and Cobra Strike's 13
(FUN_004f31a0), table 0x727ba8, take ECX the unit, EDX the skill and one
stack argument. Hooked: FUN_004648f0 (the unit's target, 12 only),
FUN_006256b0 (the state's stat list), FUN_00625d00 (the stat's value, the
count), FUN_00470390 (the overlay). Each FUN_004b9a00 call (ECX the sound,
EDX the unit) is a line's `sound`; none prints nothing. d2d's
rules::sound_ids::charge_up (components/rules/sound_ids.hpp) gives the same
(tests/test_charge_up_sound.cpp).

A case line: the cltprgfunc (12 or 13), the skill's flags byte +4, its
state (+0x80), its stat (+0x54), the state's list on the unit (1) or not,
the count, prgsound (+0x10e), a target (1) or not. The states table holds
200 rows, the stats 400.
"""
import random
import sys

from unicorn.x86_const import UC_X86_REG_ECX, UC_X86_REG_EDX

from emu import Emu

FUNCTIONS = {12: 0x4f30a0, 13: 0x4f31a0}
DATA_TABLE = 0x744304
SKILL_ROW = 0x23c
PLAY = 0x4b9a00
STATES, STATS = 200, 400
LIST = 0x5000


def gen(count, seed):
    rng = random.Random(seed)
    for _ in range(count):
        print(rng.choice((12, 13)), rng.choice((0, 4, 4, 4, 0xfb, 0xff)), rng.choice((-1, 0, 122, 199, 200, 300)),
              rng.choice((-1, 0, 318, 399, 400)), rng.choice((0, 1, 1, 1)), rng.randrange(-1, 7),
              rng.choice((0, 1, 2297, 2282, 4000)), rng.choice((0, 1, 1, 1)))


def game(path):
    emulator = Emu()
    table, skills, unit = emulator.alloc(0x1000), emulator.alloc(2 * SKILL_ROW), emulator.alloc(0x200)
    emulator.w32(DATA_TABLE, table)
    emulator.w32(table + 0xb98, skills)
    emulator.w32(table + 0xba0, 2)
    emulator.w32(table + 0xc4, STATES)
    emulator.w32(table + 0xbd4, STATS)
    row = skills + SKILL_ROW                              # skill 1
    played, case = [], {}
    emulator.hook(0x4648f0, lambda _emu: unit + 0x100 if case["target"] else 0, 0)
    emulator.hook(0x6256b0, lambda _emu: LIST if case["listed"] else 0, 2)
    emulator.hook(0x625d00, lambda _emu: case["count"] & 0xffffffff, 3)
    emulator.hook(0x470390, lambda _emu: 0, 6)

    def play(emu):
        sound = emu.mu.reg_read(UC_X86_REG_ECX)
        assert emu.mu.reg_read(UC_X86_REG_EDX) == unit  # on the caster
        played.append(str(sound - (1 << 32) if sound >> 31 else sound))
        return 0
    emulator.hook(PLAY, play, 3)
    with open(path) as lines:
        for line in lines:
            fields = [int(field) for field in line.split()]
            if len(fields) != 8:
                continue
            function, flags, state, stat, listed, count, prg_sound, target = fields
            case.update(listed=listed, count=count, target=target)
            emulator.mu.mem_write(row, bytes(SKILL_ROW))
            emulator.mu.mem_write(row + 4, bytes((flags,)))
            emulator.mu.mem_write(row + 0x80, (state & 0xffff).to_bytes(2, "little"))
            emulator.mu.mem_write(row + 0x54, (stat & 0xffff).to_bytes(2, "little"))
            emulator.mu.mem_write(row + 0x10c, (0xffff).to_bytes(2, "little"))
            emulator.mu.mem_write(row + 0x10e, prg_sound.to_bytes(2, "little"))
            played.clear()
            emulator.call(FUNCTIONS[function], 0, ecx=unit, edx=1)
            print(f"{line.strip()} =" + "".join(" " + sound for sound in played))


def inc(path):
    print("// Stock game.exe 1.14d, cltprgfunc 12 / 13's sounds (FUN_004f30a0, FUN_004f31a0);")
    print("// generated by tools/emu/charge_up_sound.py (gen 300 1, game, inc).")
    print('// { "the case line", "the sound it plays, empty for none" }')
    with open(path) as lines:
        for line in lines:
            case, answers = line.split("=")
            print(f'    {{ "{case.strip()}", "{answers.strip()}" }},')


def main():
    if len(sys.argv) == 4 and sys.argv[1] == "gen":
        gen(int(sys.argv[2]), int(sys.argv[3]))
    elif len(sys.argv) == 3 and sys.argv[1] == "game":
        game(sys.argv[2])
    elif len(sys.argv) == 3 and sys.argv[1] == "inc":
        inc(sys.argv[2])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
