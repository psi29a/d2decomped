"""A menu box's frame of boxpieces: FUN_00452e50.

    uv run python box_pieces.py gen 2000 1 > cases.tsv
    uv run python box_pieces.py [--exe PATH] game cases.tsv > g.txt   # each case line + game.exe's cels
    ../../build/tests/test_box_pieces cases.tsv | diff g.txt -
    uv run python box_pieces.py inc g.txt > ../../tests/box_pieces_cases.inc

FUN_00452e50 (fastcall, ECX a rect {left, top, last_x, last_y}) draws
UI\\menu\\boxpieces (0x7a2798) round it through FUN_004f6480(cel, x, y, -1,
5, 0), hooked and recorded: {frame, x, y}, the frame the cel's first word.
The NPC windows (FUN_004b8100) and Configure Controls call it.

A case: `seq left top last_x last_y`. `game` prints the case line, then `=`
and each cel as `frame:x:y`, in draw order.
"""
import random
import struct
import sys

import emu


def gen(count, seed):
    rng = random.Random(seed)
    for seq in range(count):
        left = rng.choice((0, 10, rng.randint(-50, 800)))
        top = rng.choice((0, 10, rng.randint(-50, 600)))
        width = rng.choice((0, 1, 24, 25, 26, 37, 38, rng.randint(0, 80), rng.randint(0, 800)))
        height = rng.choice((0, 1, 23, 24, 25, 35, 36, rng.randint(0, 80), rng.randint(0, 600)))
        print(seq, left, top, left + width - 1, top + height - 1)


def game(path, exe=None):
    e = emu.Emu(exe=exe)
    rect = e.alloc(0x10)
    cels = []

    def cel(e):                                                   # FUN_004f6480(cel, x, y, -1, 5, 0)
        esp = e.mu.reg_read(emu.UC_X86_REG_ESP)
        cels.append((e.r32(e.arg(0)), e.s32(esp + 8), e.s32(esp + 12)))
        return 0

    e.hook(0x4F6480, cel, 6)
    for line in open(path):
        seq, left, top, last_x, last_y = map(int, line.split())
        e.mu.mem_write(rect, struct.pack("<4i", left, top, last_x, last_y))
        cels.clear()
        e.call(0x452E50, ecx=rect)
        print(seq, left, top, last_x, last_y, "=", *(f"{f}:{x}:{y}" for f, x, y in cels))


def inc(path):
    print("// Stock game.exe 1.14d, FUN_00452e50; generated by tools/emu/box_pieces.py (gen 2000 1, game, inc).")
    print('// { "the case line", "frame:x:y..." }')
    for line in open(path):
        case, answers = line.split("=")
        print(f'    {{ "{case.strip()}", "{answers.strip()}" }},')


def main():
    args = sys.argv[1:]
    exe = None
    if "--exe" in args:
        at = args.index("--exe")
        exe = args[at + 1]
        del args[at:at + 2]
    if len(args) == 3 and args[0] == "gen":
        gen(int(args[1]), int(args[2]))
    elif len(args) == 2 and args[0] == "game":
        game(args[1], exe)
    elif len(args) == 2 and args[0] == "inc":
        inc(args[1])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
