"""Capture stock 1.14d overlay frames from FUN_00470c30.

Usage: uv run python overlays.py > /tmp/overlay_cases.inc &&
       cp /tmp/overlay_cases.inc ../../tests/overlay_cases.inc

Only the unit's graphics lookup, state lookup, clock and removal are stubbed.
The frame counter, wrap and kind-6 wait run in game.exe. No MPQs are read.
Reject other executables, incomplete calls and unexpected hook allocation.
"""
import argparse
import hashlib
from pathlib import Path

from unicorn.x86_const import UC_X86_REG_EIP

import emu


def main():
    """Emit C++ fixtures; fail before output if any oracle check fails."""
    argparse.ArgumentParser(description=__doc__).parse_args()
    path = Path(emu.data_path()) / "bin" / "game.exe"
    expected = "631066c1649c4ea9ffe48bf97e24c00bca1f7a6759c21150f1a79982589adaaf"
    if hashlib.sha256(path.read_bytes()).hexdigest() != expected:
        raise SystemExit("overlays: requires stock game.exe 1.14d (1.14.3.71)")
    machine = emu.Emu(str(path))
    graphics = machine.alloc(0x3c)
    overlay = machine.alloc(0xa8)
    state = {"now": 1, "removed": False}

    def remove(current):
        state["removed"] = True
        current.w32(graphics + 0x2c, 0)
        return 0

    machine.hook(0x463e10, lambda current: graphics, 0)
    machine.hook(0x46e040, remove, 2)
    machine.hook(0x639df0, lambda current: 1, 2)     # state overlay's state is still on
    # GetTickCount is an import stub: replace its handler, preserving its slot.
    clock_found = False
    for slot, (name, _handler) in list(machine.slots.items()):
        if name == "GetTickCount":
            machine.slots[slot] = (name, lambda current: (state["now"], 0))
            clock_found = True
    if not clock_found:
        raise RuntimeError("GetTickCount import was not found")
    slots = len(machine.slots)

    def begin(kind, rate, frames, wait=7000):
        machine.mu.mem_write(overlay, b"\0" * 0xa8)
        machine.w32(graphics + 0x2c, overlay)
        for offset, value in ((0, kind), (8, 1), (0xc, -1), (0x14, rate * 16),
                              (0x1c, frames * 256), (0x28, wait)):
            machine.w32(overlay + offset, value)
        # Kind 4's successor overlays must both be absent.
        if kind == 4:
            machine.w32(overlay + 8, -1)
        state["removed"] = False

    def step(now):
        state["now"] = now
        machine.call(0x470c30, ecx=1, limit=10000)
        if machine.mu.reg_read(UC_X86_REG_EIP) != emu.RET_MAGIC:
            raise RuntimeError("overlay update exceeded its instruction budget")
        counter = machine.r32(overlay + 0x18)
        return -1 if state["removed"] or counter >= machine.r32(overlay + 0x1c) else counter >> 8

    rows = []
    samples = (0, 1, 39, 40, 79, 80, 639, 640, 1119, 1120, 1159, 1160, 1199, 1200, 3999, 4000)
    for rate, frames in ((9, 16), (16, 16), (7, 5), (32, 16), (0, 16), (64, 2)):
        for kind in (3, 4, 8):
            begin(kind, rate, frames)
            tick = 0
            frame = 0
            for elapsed in samples:
                while tick < elapsed // 40:
                    tick += 1
                    frame = step(1 + tick * 40)
                rows.append(f"    {{ {elapsed}, {rate}, {frames}, {kind}, {frame} }},")

    # LoopWaitTime affects kind 6 only. Counter carries its fractional
    # remainder through the pause; a second update at the same clock skips.
    begin(6, 9, 1)
    def require(condition):
        if not condition:
            raise RuntimeError("kind-6 wait, duplicate clock or hook reuse check failed")

    require(step(41) == 0)
    counter = machine.r32(overlay + 0x18)
    require(step(41) == 0 and machine.r32(overlay + 0x18) == counter)
    require(step(81) == 0 and machine.r32(overlay + 8) == 0)
    require(step(7080) == 0 and machine.r32(overlay + 8) == 0)
    require(step(7081) == 0 and machine.r32(overlay + 8) == 1)
    require(len(machine.slots) == slots)
    print("// Stock game.exe 1.14d, FUN_00470c30; generated by tools/emu/overlays.py.")
    print("// elapsed_ms, AnimRate, frames, kind, visible frame (-1: not drawn)")
    print("\n".join(rows))


if __name__ == "__main__":
    main()
