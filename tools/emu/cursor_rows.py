"""The hand cursor's rows as game.exe's own getters read them, the oracle
for d2d's kCursorRows (apps/d2d/input/cursor_anim.hpp).

    uv run python cursor_rows.py                                  # check
    uv run python cursor_rows.py inc > ../../tests/cursor_rows_cases.inc

The rows are static data at 0x712010 (0x1c bytes each; FUN_004680b0
loads DATA\\GLOBAL\\UI\\CURSOR\\<name> for each from +0x18), followed by
their count at 0x7120d4 (7). Both getters take the row in EAX, assert the
count is 7 and the row under it, and return a field: FUN_00467e40 +4 (the
row loops), FUN_00467e90 +8 (its frames) shifted left 8 (the length in
8.8 frames, as the frame position 0x7a6ae0 counts). The other fields
(+0 animated, +0xc the step a tick, +0x10 a press plays ppress) are read
in place by FUN_004681c0 and FUN_00467f20, and printed here from the
table.
"""
import sys

import emu

LOOPS, LENGTH = 0x467E40, 0x467E90   # gaps-runs: 0x467e40 0x467e90
TABLE, COUNT, ROW = 0x712010, 0x7120D4, 0x1C


def rows(exe=None):
    e = emu.Emu(exe)
    count = e.r32(COUNT)
    if count != 7:
        raise AssertionError(f"row count at {COUNT:#x}: {count}, want 7")
    out = []
    for row in range(count):
        base = TABLE + row * ROW
        name = e.cstr(e.r32(base + 0x18))
        loops = e.call(LOOPS, regs={"eax": row}, limit=200)
        length = e.call(LENGTH, regs={"eax": row}, limit=200)
        if loops != e.r32(base + 4) or length != e.r32(base + 8) << 8:
            raise AssertionError(f"row {row}: getters {loops} {length} disagree with the table")
        out.append((row, name, e.r32(base), loops, length, e.r32(base + 0xC), e.r32(base + 0x10)))
    return out


def main(args):
    table = rows()
    if args[:1] == ["inc"]:
        print("// Stock game.exe 1.14d, FUN_00467e40 / FUN_00467e90 and the table at 0x712010; generated by tools/emu/cursor_rows.py inc.")
        print("// row, name, animated (+0), loops (FUN_00467e40), length (FUN_00467e90), step (+0xc), pressable (+0x10)")
        for row, name, animated, loops, length, step, pressable in table:
            print(f'    {{ {row}, "{name}", {animated}, {loops}, {length}, {step}, {pressable} }},')
        return 0
    for line in table:
        print(*line)
    print(f"ok: {len(table)} cursor rows")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
