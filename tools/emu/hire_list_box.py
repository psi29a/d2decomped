"""The hire window's list box: the rows that fit and the row under the mouse.

    uv run python hire_list_box.py gen 20000 1 > cases.tsv
    uv run python hire_list_box.py [--exe PATH] game cases.tsv > g.txt     # each case line + game.exe's answers
    ../../build/tests/test_hire_list_box cases.tsv | diff g.txt -
    uv run python hire_list_box.py inc g.txt > ../../tests/hire_list_box_cases.inc   # (gen 2000 1)

D2Win's ListBoxImplementation (FUN_004bf650; the hire window's, FUN_004bf8f0
from FUN_004b5c60): FUN_004be340 (fastcall, ECX the list) counts the rows
that fit from the first shown, FUN_004bea50 (thiscall, ECX the list, the
mouse event: u16 x +0xc, y +0xe; `ret 4`) finds the row under the mouse
and keeps it at +0x180738. Both run for real on a list whose fields are
set as the constructor sets them: y +0x18070c, height +0x180714, line
height +0x180766 (0xe), row gap +0x18076a, the scroll bar's x +0x18075a,
a callback +0x18074a, the rows' count (u16 +0x180748), the first shown
+0x180730, and each row's lines (row r at r * 0x300e: line k's text at
+0x8 + k * 0x800, a line counts when its first character isn't 0).

A case: `seq y height gap scroll_x first mouse_x mouse_y rows {lines...}`.
`game` prints the case line, then the rows that fit and the row under
the mouse (-1 none).
"""
import random
import struct
import sys

import emu

ROW, LINE = 0x300E, 0x800
Y, HEIGHT, LINE_H, GAP, SCROLL_X, CALLBACK, COUNT, FIRST, HOVER = 0x18070C, 0x180714, 0x180766, 0x18076A, 0x18075A, 0x18074A, 0x180748, 0x180730, 0x180738
SIZE = 0x180800


def gen(count, seed):
    rng = random.Random(seed)
    for seq in range(count):
        rows = rng.choice((0, 1, 2, 7, 8, 9, 10, rng.randint(0, 20), rng.randint(0, 128)))
        hire = rng.random() < 0.5                                  # the hire window's: two lines a row
        lines = [2 if hire else rng.choice((0, 1, 1, 2, 2, 3, 6, rng.randint(0, 6))) for _ in range(rows)]
        y = 140 if hire else rng.randint(-50, 500)
        height = 0x118 if hire else rng.choice((0, 0x10, 0x14, 0x15, 0x30, 0x118, rng.randint(0, 600)))
        gap = 6 if hire else rng.choice((0, 6, rng.randint(0, 40)))
        scroll_x = 0x290 if hire else rng.randint(0, 800)
        first = rng.randint(0, max(rows, 0)) if rng.random() < 0.7 else 0
        mouse_x = max(0, rng.choice((scroll_x - 0xf, scroll_x - 0xe, rng.randint(0, 800))))
        mouse_y = max(0, rng.randint(y - 20, y + height + 20))     # the event's u16: a screen spot, never negative
        print(seq, y, height, gap, scroll_x, first, mouse_x, mouse_y, rows, *lines)


def game(path, exe=None):
    e = emu.Emu(exe=exe)
    box = e.alloc(SIZE)
    event = e.alloc(0x20)
    e.w32(box + LINE_H, 0xE)
    e.w32(box + CALLBACK, 0x4B3660)
    last_rows = 0
    for line in open(path):
        field = list(map(int, line.split()))
        seq, y, height, gap, scroll_x, first, mouse_x, mouse_y, rows = field[:9]
        lines = field[9:9 + rows]
        for row in range(max(rows, last_rows)):                    # each row's six lines: set or cleared
            have = lines[row] if row < rows else 0
            for k in range(6):
                e.mu.mem_write(box + row * ROW + 0x8 + k * LINE, struct.pack("<H", 0x41 if k < have else 0))
        last_rows = rows
        e.w32(box + Y, y)
        e.w32(box + HEIGHT, height)
        e.w32(box + GAP, gap)
        e.w32(box + SCROLL_X, scroll_x)
        e.w32(box + FIRST, first)
        e.mu.mem_write(box + COUNT, struct.pack("<H", rows))
        e.mu.mem_write(event + 0xC, struct.pack("<HH", mouse_x & 0xFFFF, mouse_y & 0xFFFF))
        shown = e.call(0x4BE340, ecx=box)
        row_at = e.call(0x4BEA50, event, ecx=box)
        signed = lambda value: value - (1 << 32) if value >> 31 else value
        print(seq, y, height, gap, scroll_x, first, mouse_x, mouse_y, rows, *lines, "=", signed(shown), signed(row_at))


def inc(path):
    print("// Stock game.exe 1.14d, FUN_004be340 / FUN_004bea50; generated by tools/emu/hire_list_box.py (gen 2000 1, game, inc).")
    print('// { "the case line", rows shown, row under the mouse }')
    for line in open(path):
        case, answers = line.split("=")
        shown, row_at = answers.split()
        print(f'    {{ "{case.strip()}", {shown}, {row_at} }},')


def main():
    args = sys.argv[1:]
    exe = None
    if "--exe" in args:
        at = args.index("--exe")
        exe = args[at + 1]
        del args[at:at + 2]
    if len(args) == 3 and args[0] == "gen":
        gen(int(args[1]), int(args[2]))
    elif len(args) == 2 and args[0] == "game":
        game(args[1], exe)
    elif len(args) == 2 and args[0] == "inc":
        inc(args[1])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
