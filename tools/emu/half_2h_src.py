"""A missile row's Half2HSrc in stock game.exe 1.14d: FUN_0064b860's SrcDamage halved from a two-hander.

Run: export D2_MPQ_DIR=/home/gui/Projects/d2decomped/dev/data
     .venv/bin/python half_2h_src.py [--mutation-check]
     .venv/bin/python half_2h_src.py inc --out ../../tests/half_2h_src_cases.inc

With every data table loaded (drlg.boot), the block 0x64bafa..0x64bb1d of FUN_0064b860 runs for real
(FUN_006289c0 -> FUN_00628980 too) on an item unit of each weapons.txt row (type 4, +4 its Items
index), a Missiles row whose byte +5 has bit 0x40 (Half2HSrc, the loader's field at 0x662b8a: +4 bit
14) or not, and a SrcDamage at [EBP-0xc]. The claim, d2d's rules::missile_physical: the SrcDamage is
halved toward zero when the row has Half2HSrc and the item is a two-hander by weapons.txt's
`2handed` column (d2d's ItemInfo::two_handed), else kept. `inc` writes the cases for
tests/test_half_2h_src.cpp (by item code; the test reads `2handed` from the MPQs as d2d loads it).
"""
import argparse
import sys
from pathlib import Path

from unicorn.x86_const import UC_X86_REG_EBP, UC_X86_REG_ESI, UC_X86_REG_ESP

import drlg
import emu

START, END = 0x64BAFA, 0x64BB1D
SRCDAMS = (0, 1, 2, 3, 63, 64, 65, 127, 128, 255)
MUT = set()


def weapons():
    """weapons.txt's rows in order: (code, 2handed)."""
    text = emu.mpq_cache().read("data\\global\\excel\\weapons.txt").decode("latin-1").splitlines()
    head = text[0].split("\t")
    code, hands = head.index("code"), head.index("2handed")
    rows = []
    for line in text[1:]:
        field = line.split("\t")
        if len(field) > hands and field[code] and field[0] != "Expansion":
            rows.append((field[code], field[hands].strip() == "1"))
    return rows


def model(srcdam, flag, two_handed):
    """d2d's halving."""
    if "no_half" in MUT or not flag:
        return srcdam
    if not two_handed and "half_any" not in MUT:
        return srcdam
    return (srcdam + 1) // 2 if "round_up" in MUT else srcdam // 2


def game_cases(e):
    """Each weapons.txt row, flag and SrcDamage through the block: (code, flag, srcdam, result, 2handed)."""
    frame, row, item = e.alloc(0x400), e.alloc(0x200), e.alloc(0x100)
    out = []
    for index, (code, two_handed) in enumerate(weapons()):
        e.w32(item, 4)
        e.w32(item + 4, index)
        for flag in (0, 1):
            e.mu.mem_write(row + 5, bytes([0x40 if flag else 0]))
            for srcdam in SRCDAMS:
                ebp = frame + 0x200
                e.w32(ebp - 0x28, row)
                e.w32(ebp - 0xC, srcdam)
                e.mu.reg_write(UC_X86_REG_EBP, ebp)
                e.mu.reg_write(UC_X86_REG_ESP, ebp - 0x100)
                e.mu.reg_write(UC_X86_REG_ESI, item)
                e.mu.emu_start(START, END)
                out.append((code, flag, srcdam, e.r32(ebp - 0xC), two_handed))
    return out


def run(cases, mutation):
    """The model against game.exe's answers; the failure count."""
    MUT.clear()
    MUT.update(mutation)
    bad = 0
    for code, flag, srcdam, result, two_handed in cases:
        if model(srcdam, flag, two_handed) != result:
            bad += 1
            if bad <= 3 and not mutation:
                print(f"{code} flag {flag} srcdam {srcdam}: game {result}, model {model(srcdam, flag, two_handed)}")
    return bad


def main():
    """Run the oracle, with --mutation-check prove each mutant of the model is caught, or write the fixture."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", nargs="?", choices=("inc",))
    parser.add_argument("--out")
    parser.add_argument("--mutation-check", action="store_true")
    args = parser.parse_args()
    cases = game_cases(drlg.boot())
    bad = run(cases, ())
    if bad:
        print(f"FAIL: {bad} cases differ", file=sys.stderr)
        sys.exit(1)
    if args.mode == "inc":
        lines = ["// Generated by tools/emu/half_2h_src.py inc: FUN_0064b860 0x64bafa..0x64bb1d's answers from game.exe 1.14d.",
                 "// { weapons.txt code, Half2HSrc, SrcDamage, SrcDamage after }"]
        lines += [f'{{ "{code}", {flag}, {srcdam}, {result} }},' for code, flag, srcdam, result, _ in cases if srcdam in (0, 1, 3, 128, 255)]
        text = "\n".join(lines) + "\n"
        if args.out:
            Path(args.out).write_text(text)
        else:
            sys.stdout.write(text)
        return
    halved = sum(1 for code, flag, srcdam, result, _ in cases if result != srcdam)
    print(f"ok: {len(cases)} FUN_0064b860 Half2HSrc cases over {len(cases) // (2 * len(SRCDAMS))} weapons ({halved} halved)")
    if args.mutation_check:
        for name in ("no_half", "half_any", "round_up"):
            caught = run(cases, (name,))
            print(f"mutant {name}: {'caught' if caught else 'NOT CAUGHT'} ({caught})")
            if not caught:
                sys.exit(1)
        print("mutation check ok")


if __name__ == "__main__":
    main()
