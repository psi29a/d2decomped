"""Do 143's missile route (FUN_005d4680, FUN_005d4870's path callback): the
oracle for rules::wobble_route (tests/test_release_ring.cpp).

    uv run python wobble_route.py [cases] [seed] > ../../tests/wobble_route_cases.inc

FUN_005d4680 runs for real on a missile unit (type 3, its seed at +0x20 /
+0x24, its path at +0x2c), FUN_00621dc0, FUN_0064fdc0 and FUN_0063e7a0 inside
it. Hooked: the range (FUN_0064a300) and its cap's writes (FUN_0064a2b0,
FUN_0064a330), FUN_00650e40, the path's type / count setters (FUN_00648cf0,
FUN_00648e70, FUN_00648790), its point buffer (FUN_006487d0), its spot
(FUN_006488c0 / FUN_00648900) and its target (FUN_00648a00 / FUN_00648a10).
Each case prints the start, target, range, seed and the points it wrote,
then the seed after.
"""
import random
import sys

import emu


def main():
    cases = int(sys.argv[1]) if len(sys.argv) > 1 else 40
    rng = random.Random(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
    e = emu.Emu()
    state = {}
    buffer = e.alloc(0x400)
    e.hook(0x64A300, lambda h: state["range"], 1)
    e.hook(0x64A2B0, lambda h: 0, 2)
    e.hook(0x64A330, lambda h: 0, 2)
    e.hook(0x650E40, lambda h: 0, 0)
    e.hook(0x648CF0, lambda h: 0, 2)
    e.hook(0x648E70, lambda h: 0, 2)
    e.hook(0x648790, lambda h: 0, 2)

    def points_at(h):
        e.w32(h.arg(1), buffer)
        return buffer
    e.hook(0x6487D0, points_at, 2)
    e.hook(0x6488C0, lambda h: state["x"], 1)
    e.hook(0x648900, lambda h: state["y"], 1)
    e.hook(0x648A00, lambda h: state["to_x"], 1)
    e.hook(0x648A10, lambda h: state["to_y"], 1)
    unit, path = e.alloc(0x100), e.alloc(0x100)
    e.w32(unit, 3)
    e.w32(unit + 0x2C, path)
    print("// Stock game.exe 1.14d, FUN_005d4680; generated by tools/emu/wobble_route.py.")
    print("// { x, y, to_x, to_y, range, seed low, seed high, points..., seed low after, seed high after }")
    for _ in range(cases):
        x, y = rng.randrange(1000, 30000), rng.randrange(1000, 30000)
        state.update(x=x, y=y, to_x=x + rng.randrange(-40, 41), to_y=y + rng.randrange(-40, 41), range=rng.randrange(1, 90))
        low, high = rng.getrandbits(32), rng.getrandbits(32)
        e.w32(unit + 0x20, low)
        e.w32(unit + 0x24, high)
        e.call(0x5D4680, ecx=unit)
        count = min(state["range"], 0x4D)
        words = [e.r16(buffer + 4 * k) for k in range(count)], [e.r16(buffer + 4 * k + 2) for k in range(count)]
        points = ", ".join(f"{{{px}, {py}}}" for px, py in zip(*words))
        print(f"    {{ {x}, {y}, {state['to_x']}, {state['to_y']}, {state['range']}, {low}u, {high}u, {{ {points} }}, "
              f"{e.r32(unit + 0x20)}u, {e.r32(unit + 0x24)}u }},")


if __name__ == "__main__":
    main()
