"""A walker's frame in game.exe: FUN_00650840 on random paths, frame by frame.

The path's aim is set as its making does (FUN_0064fe40), then FUN_00650840 runs
until it returns 0. The chase check (FUN_006503f0, moves.py) is hooked to "go
on" and the subtile test (FUN_0064ff90) answers from the case's blocked set.
Each row is the case and, per frame, FUN_00650840's return, the 16.16 position
and the point index after it: tests/walk_step_cases.inc, which
tests/test_walk_step.cpp replays through rules::walk_frame. A walk's last
frame leaves the path's count (+0x28) 0, asserted: FUN_00650840 runs the chase
check only with points left, so a walk over never paths again (game::walk_on).

  uv run walk_step.py [cases] > ../../tests/walk_step_cases.inc
"""
import random
import sys

import emu


def main():
    cases = int(sys.argv[1]) if len(sys.argv) > 1 else 400
    rng = random.Random(0x650840)
    e = emu.Emu()
    blocked = set()
    e.hook(0x6503f0, lambda e: 1, 0)
    e.hook(0x64ff90, lambda e: 0 if (e.arg(0) & 0xffff, e.arg(0) >> 16) in blocked else 1, 2)
    print("// Stock game.exe 1.14d, FUN_00650840; generated by tools/emu/walk_step.py.")
    print("// x, y (16.16 subtiles), velocity, points, blocked subtiles, then per frame { return, x, y, point index }")
    mark = e.brk
    for _ in range(cases):
        e.brk = mark
        unit, path = e.alloc(0x100), e.alloc(0x200)
        e.w32(unit, 1); e.w32(unit + 0x2c, path)
        sub_x, sub_y = 1000 + rng.randint(-20, 20), 1000 + rng.randint(-20, 20)
        centred = rng.random() < 0.4
        x = sub_x << 16 | (0x8000 if centred else rng.randint(0, 0xffff))
        y = sub_y << 16 | (0x8000 if centred else rng.randint(0, 0xffff))
        velocity = rng.choice((0, 1, 0x40, 0x300, 0x600, 0x900, 0xc00, 0x1800, 0x3000, 0x6000, rng.randint(1, 0x8000)))
        points, at = [], (sub_x, sub_y)
        for _ in range(rng.randint(1, 6)):
            kind = rng.random()
            if kind > 0.15: at = (at[0] + rng.randint(-5, 5), at[1] + rng.randint(-5, 5))   # else the same point again
            points.append(at)
        blocked.clear()
        for _ in range(rng.choice((0, 0, 2, 8, 30))):
            blocked.add((sub_x + rng.randint(-8, 8), sub_y + rng.randint(-8, 8)))
        e.w32(path, x); e.w32(path + 4, y); e.w32(path + 0x30, unit)
        e.w32(path + 0x24, 0); e.w32(path + 0x28, len(points)); e.w32(path + 0x34, 0x20); e.w32(path + 0x3c, 0xd)
        e.w32(path + 0x7c, velocity)
        for i, (px, py) in enumerate(points): e.w32(path + 0x9c + 4 * i, py << 16 | px)
        e.call(0x64fe40, 0, ecx=path, edx=0)
        frames = []
        for _ in range(60):
            ret = e.call(0x650840, unit, 0x400)
            frames.append((ret, e.r32(path), e.r32(path + 4), e.r32(path + 0x24)))
            if not ret:
                assert e.r32(path + 0x28) == 0, "a walk over keeps its count"
                break
        pairs = lambda rows: "{ " + ", ".join(f"{{ {a}, {b} }}" for a, b in rows) + " }" if rows else "{}"
        steps = ", ".join(f"{{ {r}, 0x{fx:x}, 0x{fy:x}, {i} }}" for r, fx, fy, i in frames)
        print(f"    {{ 0x{x:x}, 0x{y:x}, {velocity}, {pairs(points)}, {pairs(sorted(blocked))}, {{ {steps} }} }},")


if __name__ == "__main__":
    main()
