"""A SrcDamage missile's owner share in stock game.exe 1.14d: FUN_0064aa60 on FUN_0064b860's record.

Run: export D2_MPQ_DIR=/path/to/the/local/game/data
     .venv/bin/python missile_owner_share.py [--mutation-check]
     .venv/bin/python missile_owner_share.py inc --out ../../tests/missile_owner_share_cases.inc

FUN_0064aa60 (ECX the record, ESI the SrcDamage after Half2HSrc, from FUN_0064b860 0x64bed9) runs
for real on a record whose every dword is a known value. The claim, d2d's
rules::missile_owner_share: with a SrcDamage other than 128, the record's elements (+0xc..+0x2c),
cold length (+0x30), poison (+0x34, +0x38), +0x40, life and mana drain (+0x44, +0x4c) and
+0x60..+0x68 become value x SrcDamage / 128 toward zero; every other dword, poison length (+0x3c)
among them, stays. `inc` writes the cases for tests/test_missile_owner_share.cpp.
"""
import argparse
import sys
from pathlib import Path

import emu

SCALE = 0x64AA60
SCALED = (0xC, 0x10, 0x18, 0x1C, 0x20, 0x24, 0x28, 0x2C, 0x30, 0x34, 0x38, 0x40, 0x44, 0x4C, 0x60, 0x64, 0x68)
RECORD = 0x70
VALUES = (0, 1, 2, 3, 7, 63, 64, 127, 128, 129, 255, 1000, 25600, -1, -3, -129)
SRCDAMS = (1, 2, 3, 32, 63, 64, 65, 96, 127, 128, 129, 192, 255, 256)
MUT = set()


def model(value, srcdam, offset):
    """d2d's share of one record dword."""
    if offset not in SCALED and "all" not in MUT:
        return value
    if srcdam == 128 or "none" in MUT:
        return value
    if "floor" in MUT:
        return value * srcdam // 128
    product = value * srcdam
    return -((-product) // 128) if product < 0 else product // 128


def game_cases(e):
    """Each value and SrcDamage through FUN_0064aa60: (value, srcdam, offset, result)."""
    record = e.alloc(RECORD)
    out = []
    for value in VALUES:
        for srcdam in SRCDAMS:
            for offset in range(0, RECORD, 4):
                e.w32(record + offset, value)
            e.call(SCALE, ecx=record, regs={"esi": srcdam})
            for offset in range(0, RECORD, 4):
                result = e.r32(record + offset)
                out.append((value, srcdam, offset, result - (1 << 32) if result >= 1 << 31 else result))
    return out


def run(cases, mutation):
    """The model against game.exe's answers; the failure count."""
    MUT.clear()
    MUT.update(mutation)
    bad = 0
    for value, srcdam, offset, result in cases:
        if model(value, srcdam, offset) != result:
            bad += 1
            if bad <= 3 and not mutation:
                print(f"value {value} srcdam {srcdam} +{offset:#x}: game {result}, model {model(value, srcdam, offset)}")
    return bad


def main():
    """Run the oracle, with --mutation-check prove each mutant of the model is caught, or write the fixture."""
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", nargs="?", choices=("inc",))
    parser.add_argument("--out")
    parser.add_argument("--mutation-check", action="store_true")
    args = parser.parse_args()
    cases = game_cases(emu.Emu())
    bad = run(cases, ())
    if bad:
        print(f"FAIL: {bad} cases differ", file=sys.stderr)
        sys.exit(1)
    if args.mode == "inc":
        lines = ["// Generated by tools/emu/missile_owner_share.py inc: FUN_0064aa60's answers from game.exe 1.14d.",
                 "// { value, SrcDamage, value after } for a scaled dword (fire min, +0xc)"]
        lines += [f"{{ {value}, {srcdam}, {result} }}," for value, srcdam, offset, result in cases if offset == 0xC]
        text = "\n".join(lines) + "\n"
        if args.out:
            Path(args.out).write_text(text)
        else:
            sys.stdout.write(text)
        return
    print(f"ok: {len(cases)} FUN_0064aa60 record dwords over {len(VALUES)} values x {len(SRCDAMS)} SrcDamages")
    if args.mutation_check:
        for name in ("all", "none", "floor"):
            caught = run(cases, (name,))
            print(f"mutant {name}: {'caught' if caught else 'NOT CAUGHT'} ({caught})")
            if not caught:
                sys.exit(1)
        print("mutation check ok")


if __name__ == "__main__":
    main()
