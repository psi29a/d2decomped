"""Hit function 26, Grim Ward's start (FUN_005ab8d0): the oracle for test_grim_ward_start.

    uv run python hit_grim_ward.py > ../../tests/hit_grim_ward_cases.inc

FUN_005ab8d0 runs for real (ECX a game, EDX the missile: its class a Missiles.txt
row with pSrvHitFunc 26) with game.exe's tables loaded (skill_tips.boot). Hooked:
the owner (FUN_00552fd0), the missile's skill and level (FUN_0064a280: 0x5a,
FUN_0064a210: 1), the calc (FUN_00646ca0: asserts it is handed skill +0x138,
calc1, and returns the case's value), the start subtile (FUN_0045adf0 /
FUN_0045ae20: 100, 200) and the maker FUN_0059fa30, which records the params
block (EDX): flags [0], row [4], start [5] / [6], range [0x13]. Each row with
pSrvHitFunc 26 (Missiles.txt +0xe), its sHitPar1 (+0x4c) set to -1, 0, 1, 3
and 9, under calc1 results -3 .. 8.
"""
import skill_tips


def main():
    e = skill_tips.boot()
    tables = e.r32(0x744304)
    records, count = e.r32(tables + 0xB64), e.r32(tables + 0xB6C)
    skills = e.r32(tables + 0xB98)
    game, owner, missile = e.alloc(0x100), e.alloc(0x100), e.alloc(0x100)
    made, calc1 = [], [0]

    def maker(h):
        params = h.mu.reg_read(skill_tips.emu.UC_X86_REG_EDX)
        made.append([h.r32(params + 4 * k) for k in range(0x17)])
        return 1

    def calc(h):
        assert h.arg(0) == owner and h.arg(1) == h.r32(skills + 0x5A * 0x23C + 0x138) and (h.arg(2), h.arg(3)) == (0x5A, 1)
        return calc1[0] & 0xFFFFFFFF

    e.hook(0x552FD0, lambda h: owner, 0)
    e.hook(0x64A280, lambda h: 0x5A, 1)
    e.hook(0x64A210, lambda h: 1, 1)
    e.hook(0x646CA0, calc, 4)
    e.hook(0x45ADF0, lambda h: 100, 0)
    e.hook(0x45AE20, lambda h: 200, 0)
    e.hook(0x59FA30, maker, 0)
    e.w32(missile, 3)
    print("// Stock game.exe 1.14d, FUN_005ab8d0; generated by tools/emu/hit_grim_ward.py.")
    print("// { row, sHitPar1, calc1, flags, range } the one missile made")
    for row in range(count):
        record = records + row * 0x1A4
        if e.r16(record + 0xE) != 26:
            continue
        e.w32(missile + 4, row)
        for hit_par1 in (-1, 0, 1, 3, 9):
            e.w32(record + 0x4C, hit_par1 & 0xFFFFFFFF)
            for value in range(-3, 9):
                calc1[0] = value
                made.clear()
                assert e.call(0x5AB8D0, 0, ecx=game, edx=missile) == 1 and len(made) == 1
                field = made[0]
                assert field[4] == e.r16(record + 0x24) and (field[5], field[6]) == (100, 200)
                print(f"    {{ {row}, {hit_par1}, {value}, {field[0]:#x}, {field[0x13]} }},")


if __name__ == "__main__":
    main()
