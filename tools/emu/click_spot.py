"""Where a click on the ground walks to: game.exe 1.14d's FUN_004623c0 run by its own code.

    uv run python click_spot.py > ../../tests/click_spot_cases.inc
    uv run python click_spot.py | diff - ../../tests/click_spot_cases.inc     # re-check

FUN_004623c0 (stack the player unit, EBX the mouse context: flags +0, the
spot's subtile +0xc / +0x10) moves the spot out to a least distance before
FUN_00461840 paths to it (collision.md "What a held frame sends"). Runs
natively: the dead-zone tests, FUN_00474080 (the distance), the least
distance by flag, the x87 scale and FUN_00682fd0 (the truncation), and
GetXPos / GetYPos (0x6488c0 / 0x648900) on a real dynamic path, as
click_move.py sets one up. The unit stands (mode 0), so the held-frame
throttle never answers 0 (click_move.py covers it).

Every step within 12 subtiles on each axis, the 0xff / 0x100 edges, for a
press, a running press, held, held running, a release and no flag, from a
unit at (1000, 2000). Each line is {dx, dy, flags, sent, spot dx, spot dy}:
sent 0 leaves the spot as it was. d2d's rules::click_spot
(components/rules/world/click_spot.hpp) is checked against these by
tests/test_click_spot.cpp.
"""
import emu

ORIGIN_X, ORIGIN_Y = 1000, 2000
CLOCK, LAST_INDEX = 0x7A0498, 0x7A5268      # click_move.py: GetEntryIndex's clock, the throttle's stamp
FLAGS = (0, 0x4, 0x44, 0x8, 0x48, 0x10)
EDGES = (-0x100, -0xFF, 0xFF, 0x100)


def steps():
    near = range(-12, 13)
    for delta_x in near:
        for delta_y in near:
            yield delta_x, delta_y
    for edge in EDGES:
        for other in (0, 3, -0xFF):
            yield edge, other
            yield other, edge


def main():
    machine = emu.Emu()
    unit = machine.alloc(0x100)
    path = machine.alloc(0x200)
    ctx = machine.alloc(0x40)
    machine.view("unit", unit).type = 0                 # a player: a dynamic path
    machine.view("unit", unit).path = path
    machine.view("unit", unit).mode = 0                 # standing: no throttle
    machine.view("path", path).x, machine.view("path", path).y = ORIGIN_X, ORIGIN_Y
    print("// Stock game.exe 1.14d, FUN_004623c0; generated by tools/emu/click_spot.py.")
    print("// dx, dy, flags, sent, spot dx, spot dy (from the unit's subtile)")
    for delta_x, delta_y in steps():
        for flags in FLAGS:
            machine.w32(ctx, flags)
            machine.w32(ctx + 0xC, (ORIGIN_X + delta_x) & 0xFFFFFFFF)
            machine.w32(ctx + 0x10, (ORIGIN_Y + delta_y) & 0xFFFFFFFF)
            machine.w32(CLOCK, 100)
            machine.w32(LAST_INDEX, 0)
            sent = machine.call(0x4623C0, unit, regs={"ebx": ctx}) & 0xFFFFFFFF
            spot_x = machine.r32(ctx + 0xC) - ORIGIN_X
            spot_y = machine.r32(ctx + 0x10) - ORIGIN_Y
            print(f"    {{ {delta_x}, {delta_y}, 0x{flags:x}, {sent}, {spot_x}, {spot_y} }},")


if __name__ == "__main__":
    main()
