"""Hit function 2's ring (FUN_005a9d80 -> FUN_005a9370): the oracle for test_plague_ring.

    uv run python hit_ring.py > ../../tests/hit_ring_cases.inc

FUN_005a9d80 runs for real (ECX a game, EDX the missile: type 3, its class a
Missiles.txt row with pSrvHitFunc 2; no unit struck) with game.exe's tables
loaded (skill_tips.boot), FUN_005a9370 inside it. Hooked: the owner
(FUN_00552fd0), the missile's skill and level (FUN_0064a280: 0x5a,
FUN_0064a210: 1), the start subtile (FUN_0045adf0 / FUN_0045ae20: 100, 200)
and the maker FUN_0059fa30, which records each params block (EDX): flags
[0], row [4], start [5] / [6], way [7] / [8], velocity [10], loops [0xd].
Every row with pSrvHitFunc 2 (Missiles.txt +0xe).
"""
import skill_tips


def main():
    e = skill_tips.boot()
    tables = e.r32(0x744304)
    records, count = e.r32(tables + 0xB64), e.r32(tables + 0xB6C)
    game, owner, missile = e.alloc(0x100), e.alloc(0x100), e.alloc(0x100)
    made = []

    def maker(h):
        params = h.mu.reg_read(skill_tips.emu.UC_X86_REG_EDX)
        field = [h.r32(params + 4 * k) for k in range(0x17)]
        made.append(field)
        return 1

    signed = lambda value: value - (1 << 32) if value >> 31 else value
    e.hook(0x552FD0, lambda h: owner, 0)
    e.hook(0x64A280, lambda h: 0x5A, 1)
    e.hook(0x64A210, lambda h: 1, 1)
    e.hook(0x45ADF0, lambda h: 100, 0)
    e.hook(0x45AE20, lambda h: 200, 0)
    e.hook(0x59FA30, maker, 0)
    e.w32(missile, 3)
    print("// Stock game.exe 1.14d, FUN_005a9d80 -> FUN_005a9370; generated by tools/emu/hit_ring.py.")
    print("// { row, flags, way x, way y, velocity, loops } a missile made, in order")
    for row in range(count):
        if e.r16(records + row * 0x1A4 + 0xE) != 2:
            continue
        e.w32(missile + 4, row)
        made.clear()
        e.call(0x5A9D80, 0, ecx=game, edx=missile)
        for field in made:
            assert field[4] == e.r16(records + row * 0x1A4 + 0x24) and (field[5], field[6]) == (100, 200)
            print(f"    {{ {row}, {field[0]:#x}, {signed(field[7])}, {signed(field[8])}, {field[10]}, {field[0xD]} }},")


if __name__ == "__main__":
    main()
