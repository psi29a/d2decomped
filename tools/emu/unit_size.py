"""A unit's footprint height (FUN_006205a0), as the oracle.

    uv run python unit_size.py gen 400 1 > cases.tsv
    uv run python unit_size.py [--exe PATH] game cases.tsv > g.txt   # each case line + game.exe's height
    ../../build/tests/test_unit_size cases.tsv | diff g.txt -
    uv run python unit_size.py inc g.txt > ../../tests/unit_size_cases.inc

FUN_006205a0(unit) (stdcall) switches on the unit's type (+0): a player 2,
an item 1; a monster FUN_00451fe0(class) then the row's byte +9 (signed);
an object the record at *(unit +0x14), +0xd4; a missile FUN_0046ace0(class)
then the row's byte +0x18a (unsigned); else 0. All three run for real, on
a fake data-tables block (the pointer at 0x744304): MonStats (+0xa78, rows
of 0x1a8, +0x18 a short MonStats2 index; count +0xa80), MonStats2 (+0xa90,
rows of 0x134; count +0xa98), Missiles (+0xb64, rows of 0x1a4; count
+0xb6c). The column names are the loaders' (objects.txt FUN_0063f690,
MonStats2 FUN_006571a0, Missiles FUN_00661b20); the oracle doesn't need them.

A case: `seq type value miss`. `value` goes in the row's height field (a
byte for a monster or a missile, a dword for an object). `miss` is how a
monster's or a missile's lookup fails: 0 it doesn't, 1 class -1, 2 class
past the count, 3 (monster) MonStats2 index -1, 4 (monster) index past the
count. `game` prints the case line, `=`, and game.exe's answer (signed).
A null unit asserts (0x74b) and isn't a case.
"""
import random
import struct
import sys

import emu

UNIT_SIZE_Y, TABLES = 0x6205A0, 0x744304
MONSTATS, MONSTATS_N, MONSTATS2, MONSTATS2_N, MISSILES, MISSILES_N = 0xA78, 0xA80, 0xA90, 0xA98, 0xB64, 0xB6C
ROWS = 4                                     # rows in each fake table


def gen(count, seed):
    rng = random.Random(seed)
    for seq in range(count):
        kind = rng.choice((0, 1, 1, 1, 2, 2, 2, 3, 3, 3, 4, 5, 6, 7, 0xFF))
        if kind == 2:
            value = rng.choice((0, 1, 2, 3, 4, 7, 9, rng.randrange(0, 1 << 32)))
        else:
            value = rng.choice((0, 1, 2, 3, 5, 0x7F, 0x80, 0xFF, rng.randrange(256)))
        miss = 0
        if kind == 1 and rng.random() < 0.3:
            miss = rng.randint(1, 4)
        elif kind == 3 and rng.random() < 0.3:
            miss = rng.randint(1, 2)
        print(seq, kind, value, miss)


def game(path, exe=None):
    e = emu.Emu(exe=exe)
    tables = e.alloc(0x1000)
    monstats, monstats2, missiles = e.alloc(0x1A8 * ROWS), e.alloc(0x134 * ROWS), e.alloc(0x1A4 * ROWS)
    for offset, value in ((MONSTATS, monstats), (MONSTATS_N, ROWS), (MONSTATS2, monstats2), (MONSTATS2_N, ROWS),
                          (MISSILES, missiles), (MISSILES_N, ROWS)):
        e.w32(tables + offset, value)
    e.w32(TABLES, tables)
    unit, objdata, objrecord = e.alloc(0x100), e.alloc(0x10), e.alloc(0x200)
    e.w32(unit + 0x14, objdata)
    e.w32(objdata, objrecord)
    for line in open(path):
        seq, kind, value, miss = map(int, line.split())
        rng = random.Random(seq)
        row = rng.randrange(ROWS)
        index = rng.randrange(ROWS)
        cls = {1: -1, 2: ROWS + rng.randrange(3)}.get(miss, row)
        e.w32(unit, kind)
        e.w32(unit + 4, cls)
        if kind == 1:
            index = {3: -1, 4: ROWS + rng.randrange(3)}.get(miss, index)
            e.mu.mem_write(monstats + row * 0x1A8 + 0x18, struct.pack("<h", index))
            if 0 <= index < ROWS:
                e.mu.mem_write(monstats2 + index * 0x134 + 9, bytes([value & 0xFF]))
        elif kind == 2:
            e.w32(objrecord + 0xD4, value)
        elif kind == 3 and 0 <= cls < ROWS:
            e.mu.mem_write(missiles + cls * 0x1A4 + 0x18A, bytes([value & 0xFF]))
        answer = e.call(UNIT_SIZE_Y, unit)
        print(seq, kind, value, miss, "=", answer - (1 << 32) if answer & 0x80000000 else answer)


def inc(path):
    print("// Stock game.exe 1.14d, FUN_006205a0 (FUN_00451fe0 / FUN_0046ace0 run too);")
    print("// generated by tools/emu/unit_size.py (gen 400 1, game, inc).")
    print('// { "the case line", the height }')
    for line in open(path):
        case, answer = line.split("=")
        print(f'    {{ "{case.strip()}", {int(answer)} }},')


def main():
    args = sys.argv[1:]
    exe = None
    if "--exe" in args:
        at = args.index("--exe")
        exe = args[at + 1]
        del args[at:at + 2]
    if len(args) == 3 and args[0] == "gen":
        gen(int(args[1]), int(args[2]))
    elif len(args) == 2 and args[0] == "game":
        game(args[1], exe)
    elif len(args) == 2 and args[0] == "inc":
        inc(args[1])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
