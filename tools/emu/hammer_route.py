"""Blessed Hammer's route (FUN_005d0040 gives its path type 14, FUN_00649760
-> FUN_0067a140): the oracle for rules::hammer_route (tests/test_hammer_route.cpp).

    uv run python hammer_route.py [cases] [seed] > ../../tests/hammer_route_cases.inc

FUN_0067a140 runs for real on a path (its 16.16 spot at +0 / +4, a subtile's
centre as a missile starts); it writes its points at +0x9c and their count
at +0x28. Each case prints the start subtile and the points.
"""
import random
import sys

import emu


def main():
    cases = int(sys.argv[1]) if len(sys.argv) > 1 else 8
    rng = random.Random(int(sys.argv[2]) if len(sys.argv) > 2 else 1)
    e = emu.Emu()
    path = e.alloc(0x200)
    print("// Stock game.exe 1.14d, FUN_0067a140; generated by tools/emu/hammer_route.py.")
    print("// { x, y, points... }")
    for _ in range(cases):
        x, y = rng.randrange(1000, 30000), rng.randrange(1000, 30000)
        e.w32(path, (x << 16) + 0x8000)
        e.w32(path + 4, (y << 16) + 0x8000)
        e.call(0x67A140, ecx=path)
        count = e.r32(path + 0x28)
        points = ", ".join(f"{{{e.r16(path + 0x9C + 4 * k)}, {e.r16(path + 0x9E + 4 * k)}}}" for k in range(count))
        print(f"    {{ {x}, {y}, {{ {points} }} }},")


if __name__ == "__main__":
    main()
