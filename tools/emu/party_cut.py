"""The Party screen's text cuts run natively: a row's name (FUN_0049a2c0) and a member's area (FUN_0049a830).

    uv run python party_cut.py [cases] [seed] [--dump ../../tests/party_cut_cases.inc]

Each case is a random name (1..15 letters, in a party or not) or area name
(1..30). The font is hooked: FUN_00501820 measures a letter c as
5 + c % 9 px, the rule tests/test_party_cut.cpp gives d2d's
client::cut_party_name / cut_party_area. Also hooked, as plain unit-string
copies: FUN_00526320 (text to units, at most n), FUN_005267e0 (copy),
FUN_00526700 (append), FUN_00526800 (length), FUN_00453e70 (the area's
string, the row's level +0xc1). FUN_00502320 (draw) records what it's given.
A line: kind (0 name, 1 area), in a party, the text, what's drawn.
"""
import random
import string
import sys

from unicorn.x86_const import UC_X86_REG_ECX, UC_X86_REG_EDX

import emu

LETTERS = string.ascii_letters + string.digits + " "


def width(text):
    return sum(5 + ord(c) % 9 for c in text)


def units(e, a):
    out = []
    while (u := e.r16(a + 2 * len(out))):
        out.append(chr(u))
    return "".join(out)


def write_units(e, a, text):
    e.mu.mem_write(a, (text + "\0").encode("utf-16-le"))


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dump = sys.argv[sys.argv.index("--dump") + 1] if "--dump" in sys.argv else None
    if dump: args.remove(dump)
    cases, seed = int(args[0]) if args else 2000, int(args[1]) if len(args) > 1 else 1
    rng = random.Random(seed)
    e = emu.Emu()
    drawn = []

    def ecx(): return e.mu.reg_read(UC_X86_REG_ECX)
    def edx(): return e.mu.reg_read(UC_X86_REG_EDX)

    def to_units(e):                                             # FUN_00526320(ECX dst, EDX text, n)
        write_units(e, ecx(), e.cstr(edx())[:e.arg(0)])
        return ecx()

    area = {}
    e.hook(0x526320, to_units, 1)
    e.hook(0x5267E0, lambda e: write_units(e, ecx(), units(e, edx())) or ecx(), 0)
    e.hook(0x526700, lambda e: write_units(e, ecx(), units(e, ecx()) + units(e, edx())) or ecx(), 0)
    e.hook(0x526800, lambda e: len(units(e, ecx())), 0)
    e.hook(0x501820, lambda e: width(units(e, ecx())), 0)
    e.hook(0x453E70, lambda e: area[ecx()], 0)
    e.hook(0x502320, lambda e: drawn.append(units(e, ecx())) or 0, 3)
    text_at, entry = e.alloc(0x200), e.alloc(0x100)
    lines = []
    for _ in range(cases):
        kind, in_party = rng.randrange(2), rng.randrange(2)
        text = "".join(rng.choice(LETTERS) for _ in range(rng.randint(1, 15 if kind == 0 else 30)))
        drawn.clear()
        if kind == 0:
            e.mu.mem_write(text_at, text.encode("latin-1") + b"\0")
            e.call(0x49A2C0, 0x5A, 2, in_party, edx=text_at)
        else:
            in_party = 1
            write_units(e, text_at, text)
            area[7] = text_at
            e.w32(entry + 0xC1, 7)
            e.call(0x49A830, entry, 2, regs={"eax": 0x5A})
        lines.append(f'    {{ {kind}, {in_party}, "{text}", "{drawn[0]}" }},')
    out = open(dump, "w") if dump else sys.stdout
    print(f"// Stock game.exe 1.14d, FUN_0049a2c0 / FUN_0049a830; generated by tools/emu/party_cut.py {cases} {seed}.", file=out)
    print("// kind (0 name, 1 area), in a party, the text, what game.exe draws", file=out)
    print("\n".join(lines), file=out)


if __name__ == "__main__":
    main()
