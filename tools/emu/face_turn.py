"""An action's facing outside a walk: game.exe turns toward it, a step a frame.

The client's MonsterMessage (FUN_004aff60) faces a mode at a unit through
FaceTarget (FUN_00465bf0, EDX 0) and one at a point through FUN_00621c00;
both end in FUN_00649ef0(path, x, y, 0): the 64-step aim from the path's
16.16 place at the subtile's centre (FUN_0064fe10 -> FUN_0064fc60) handed to
FUN_006485f0, which for a player's (type 0) or monster's (type 1) path sets
only the goal (+0x65) and the step (+0x66, DIFFDIRECTIONS 0x6eb548), leaving
+0x64; FUN_00648640 turns it each client frame (FUN_004b13a0). This runs
those for real on random places, facings and subtiles, then 10 frames of the
turn, and compares a model of d2d's turn_to + turn_frame (ai.cpp).

  .venv/bin/python face_turn.py [--mutation-check]
  .venv/bin/python face_turn.py inc --out ../../tests/face_turn_cases.inc

`inc` writes the fixture tests/game/test_face_turn.cpp replays through
d2d's own turn_to and turn_frame, only after a passing run.
`--mutation-check` breaks the model one way at a time (the old snap among
them) and requires each to fail.
"""
import argparse
import random
import sys

import emu

FRAMES = 10
CASES = 3000
mutation = None


def model(e, diff, kind, x, y, now, goal, step, to_x, to_y):
    """d2d's turn_to then turn_frame per frame: the facing's (now, goal) after each."""
    out = e.alloc(16)
    aim_x = (to_x << 16) + (0 if mutation == "corner" else 0x8000)
    aim_y = (to_y << 16) + (0 if mutation == "corner" else 0x8000)
    e.call(0x64fc60, x, y, aim_x, aim_y, ecx=out, edx=out + 8)       # rules::aim_direction (facing.py)
    dir64 = e.r32(out + 8) & 0x3F
    if mutation == "snap" or (mutation == "player-snaps" and kind == 0):
        now = goal = dir64                                            # the old face(): now and goal at once
    elif dir64 != goal or mutation == "no-early-return":
        base = goal if mutation == "step-from-goal" else now
        goal, step = dir64, diff[(dir64 - base) & 0x3F]
    frames = []
    for _ in range(FRAMES):
        if now != goal:                                               # Facing::turn (FUN_00648640)
            now = (now + step) & 0x3F
            left = (now - goal) & 0x3F
            if (left > 0x1F and step > 0x3F) or (left < 0x1F and step < 0x3F):
                now = goal
        frames.append((now, goal))
    return frames


def cases(rng):
    """Random places (16.16 subtiles), facings and subtiles to face, both unit types."""
    for _ in range(CASES):
        kind = rng.choice((0, 1))
        x = (1000 + rng.randint(-40, 40)) << 16 | (0x8000 if rng.random() < 0.5 else rng.randint(0, 0xFFFF))
        y = (1000 + rng.randint(-40, 40)) << 16 | (0x8000 if rng.random() < 0.5 else rng.randint(0, 0xFFFF))
        now = rng.randint(0, 63)
        goal = now if rng.random() < 0.6 else rng.randint(0, 63)
        started = now if rng.random() < 0.6 else rng.randint(0, 63)   # a turn under way: its step from where it began
        to_x = (x >> 16) + rng.randint(-12, 12)
        to_y = (y >> 16) + rng.randint(-12, 12)
        yield kind, x, y, now, goal, started, to_x, to_y


def run(write=None):
    """Run every case on game.exe and the model; the first difference raises."""
    e = emu.Emu()
    diff = [e.r32(0x6EB548 + 4 * i) & 0xFF for i in range(64)]
    unit_at, path_at = e.alloc(0x100), e.alloc(0x200)
    path = e.view("path", path_at)
    path.owner, path.flags = unit_at, 0
    rng = random.Random(0x649EF0)
    rows = []
    for kind, x, y, now, goal, started, to_x, to_y in cases(rng):
        e.view("unit", unit_at).type = kind
        e.w32(path_at, x)
        e.w32(path_at + 4, y)
        step = diff[(goal - started) & 0x3F]
        path.facing, path.facing_goal, path.turn_step = now, goal, step
        e.call(0x649EF0, path_at, to_x, to_y, 0)                      # FUN_00649ef0(path, x, y, 0) -> FUN_006485f0
        game = []
        for _ in range(FRAMES):
            e.call(0x648640, path_at)                                 # FUN_00648640
            game.append((path.facing, path.facing_goal))
        ours = model(e, diff, kind, x, y, now, goal, step, to_x, to_y)   # steps as the path's bytes
        if game != ours:
            raise RuntimeError(f"type {kind} at {x:#x},{y:#x} now {now} goal {goal} -> ({to_x}, {to_y}): game {game}, model {ours}")
        rows.append((kind, x, y, now, goal, step, to_x, to_y, game))
    if write:
        with open(write, "w") as out:
            out.write("// Stock game.exe 1.14d; generated by tools/emu/face_turn.py.\n")
            out.write("// type, x, y (16.16), now, goal, step (a byte), the subtile faced; then (now, goal) after each of 10 FUN_00648640 frames.\n")
            out.write("inline constexpr FaceTurnCase kFaceTurnCases[] = {\n")
            for kind, x, y, now, goal, step, to_x, to_y, game in rows[:400]:
                steps = ", ".join(f"{{ {at}, {to} }}" for at, to in game)
                out.write(f"    {{ {kind}, 0x{x:x}, 0x{y:x}, {now}, {goal}, {step}, {to_x}, {to_y}, {{ {steps} }} }},\n")
            out.write("};\n")
    return len(rows)


def main():
    """Entry point: the check, the fixture, or every mutation required to fail."""
    global mutation
    parser = argparse.ArgumentParser()
    parser.add_argument("what", nargs="?", choices=("check", "inc"), default="check")
    parser.add_argument("--out")
    parser.add_argument("--mutation-check", action="store_true")
    args = parser.parse_args()
    count = run(args.out if args.what == "inc" else None)
    print(f"ok: {count} FUN_00649ef0 -> FUN_006485f0 turns, {FRAMES} FUN_00648640 frames each")
    if args.what == "inc":
        print(f"wrote {args.out}")
    if args.mutation_check:
        for name in ("snap", "player-snaps", "corner", "no-early-return", "step-from-goal"):
            mutation = name
            try:
                run()
            except RuntimeError:
                print(f"mutation {name}: failed as required")
            else:
                raise SystemExit(f"mutation {name} was not caught")
            finally:
                mutation = None


if __name__ == "__main__":
    sys.exit(main())
