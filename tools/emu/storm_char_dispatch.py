"""Storm's message dispatch with the chat box's and the NPC menu's WM_CHAR handlers (FUN_00426420, FUN_00426f90).

    .venv/bin/python storm_char_dispatch.py [--exe PATH] [--mutation-check] [inc > ../../tests/storm_char_dispatch_cases.inc]

Registers two handlers for tag 0x534d5347 (any message), code 0x102 (WM_CHAR)
with game.exe's own FUN_00426420 (the chat box's FUN_0047ca70 and the menu's
FUN_004b7a90, in both orders), then dispatches one WM_CHAR with FUN_00426f90.
The handlers are hooked and record that they ran; each sets the message's
"handled" word (+0x18) as the real ones do. Observed: every handler of the
code runs, the newest registered first, handled or not. Allocation, free and
the critical section are scripted; nothing else is.
"""
import argparse
import sys

import emu

TAG_ANY, HWND, WM_CHAR, WM_KEYDOWN = 0x534D5347, 0x1234, 0x102, 0x100
CHAT, MENU, OTHER = 0x47CA70, 0x4B7A90, 0x4B79D0
REAL = (0x426420, 0x426F90, 0x426270, 0x426C80, 0x426F20)


def run_case(exe, order, mutation):
    """Register the handlers of `order` (oldest first), dispatch a WM_CHAR; return the handlers that ran, in order."""
    machine = emu.Emu(exe, real=REAL)
    ran = []

    def allocate(current):
        """FUN_00413020: a fresh block (the source name and line are ignored)."""
        return current.alloc(max(current.arg(0), 1))

    machine.hook(0x413020, allocate, 4)
    machine.hook(0x412650, lambda current: 1, 4)
    for address in (CHAT, MENU, OTHER):
        def handler(current, address=address):
            """Record the call and set the message's handled word, as FUN_00420290 does."""
            ran.append(address)
            current.w32(current.arg(0) + 0x18, 1)
            return 0
        machine.hook(address, handler, 1)
    for address in order:
        # Storm's SEVT register: (tag, window, code, 0, handler), ret 0x14.
        machine.call(0x426420, TAG_ANY, HWND, WM_CHAR, 0, address, limit=2_000_000)
    # A key-down handler of the same window must not run for a WM_CHAR.
    machine.call(0x426420, TAG_ANY, HWND, WM_KEYDOWN, 0, OTHER, limit=2_000_000)
    message = machine.alloc(0x40)
    machine.call(0x426F90, TAG_ANY, HWND, WM_CHAR, message, limit=2_000_000)
    if mutation == "stop at handled":
        del ran[1:]
    if mutation == "oldest first":
        ran.reverse()
    return ran


def main():
    """Run the cases and check them; `inc` prints the C++ fixtures; --mutation-check proves the mutants are caught."""
    parser = argparse.ArgumentParser()
    parser.add_argument("mode", nargs="?", choices=("check", "inc"), default="check")
    parser.add_argument("--exe")
    parser.add_argument("--mutation-check", action="store_true")
    args = parser.parse_args()
    orders = ((CHAT, MENU), (MENU, CHAT), (MENU,), (CHAT,))

    def check(mutation):
        """Each order's observation against the rule: all, newest first."""
        rows = []
        for order in orders:
            ran = run_case(args.exe, order, mutation)
            if ran != list(reversed(order)):
                raise AssertionError(f"registered {[hex(a) for a in order]}: ran {[hex(a) for a in ran]}")
            rows.append((order, ran))
        return rows

    rows = check(None)
    if args.mode == "inc":
        print("// Stock game.exe 1.14d, FUN_00426420 + FUN_00426f90; generated by tools/emu/storm_char_dispatch.py.")
        print("// { the chat box registered, the menu registered, the chat box is registered first (1) or last (0), chat ran, menu ran, the one that ran first (1 chat, 2 menu) }")
        for order, ran in rows:
            chat_first = order.index(CHAT) == 0 if CHAT in order and MENU in order else 0
            print(f"    {{ {int(CHAT in order)}, {int(MENU in order)}, {int(chat_first)}, {int(CHAT in ran)}, {int(MENU in ran)}, {1 if ran[0] == CHAT else 2} }},")
        return
    print(f"ok: {len(rows)} registrations, every WM_CHAR handler ran, newest first")
    if args.mutation_check:
        for mutation in ("stop at handled", "oldest first"):
            try:
                check(mutation)
            except AssertionError:
                print(f"negative control caught: {mutation}")
            else:
                sys.exit(f"negative control escaped: {mutation}")


if __name__ == "__main__":
    main()
