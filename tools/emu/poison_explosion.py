"""Poison Explosion (do 63, FUN_005c5e60 -> FUN_005a9370): the oracle for test_poison_explosion.

    uv run python poison_explosion.py > ../../tests/poison_explosion_cases.inc

FUN_005c5e60 runs for real (ECX a game, EDX the caster; stack the skill id and its level) with
game.exe's tables loaded (skill_tips.boot), FUN_005a9370 inside it. Hooked: the target unit
(FUN_00553540: the corpse, or none), the corpse test (FUN_00645680), the state put on it
(FUN_00639db0, recorded), FUN_0064c040, the corpse's subtile (FUN_0045adf0 / FUN_0045ae20: 100,
200) and the maker FUN_0059fa30, which records each params block (EDX): flags [0], row [4], start
[5] / [6], way [7] / [8], velocity [10], life [0xd]. The cases: Poison Explosion (row 83) at levels 1, 10 and 20 with no unit, a unit the
corpse test refuses, and a corpse.
"""
import skill_tips


def main():
    e = skill_tips.boot()
    game, caster, corpse = e.alloc(0x100), e.alloc(0x100), e.alloc(0x100)
    made, states = [], []
    unit = {"found": corpse, "corpse": 1}

    def maker(h):
        params = h.mu.reg_read(skill_tips.emu.UC_X86_REG_EDX)
        made.append([h.r32(params + 4 * k) for k in range(0x17)])
        return 1

    def put_state(h):
        states.append((h.arg(0), h.arg(1), h.arg(2)))
        return 1

    signed = lambda value: value - (1 << 32) if value >> 31 else value
    e.hook(0x553540, lambda h: unit["found"], 2)
    e.hook(0x645680, lambda h: unit["corpse"], 1)
    e.hook(0x639DB0, put_state, 3)
    e.hook(0x64C040, lambda h: 0, 1)
    e.hook(0x45ADF0, lambda h: 100, 0)
    e.hook(0x45AE20, lambda h: 200, 0)
    e.hook(0x59FA30, maker, 0)

    def case(skill, level, kind):
        unit["found"], unit["corpse"] = (0, 0) if kind == 0 else (corpse, int(kind == 2))
        made.clear()
        states.clear()
        returned = e.call(0x5C5E60, skill, level, ecx=game, edx=caster)
        state = 0
        for put_on, put, value in states:
            assert put_on == corpse and value == 1
            state = put
        if not made:
            print(f"    {{ {skill}, {level}, {kind}, {returned}, {state:#x}, -1, 0, 0, 0, 0, 0 }},")
        for field in made:
            assert (field[5], field[6]) == (100, 200) and field[1] == caster and field[2] == corpse
            print(f"    {{ {skill}, {level}, {kind}, {returned}, {state:#x}, {field[4]}, {field[0]:#x}, "
                  f"{signed(field[7])}, {signed(field[8])}, {field[10]}, {field[0xD]} }},")

    print("// Stock game.exe 1.14d, FUN_005c5e60 -> FUN_005a9370; generated by tools/emu/poison_explosion.py.")
    print("// { skill, level, unit (0 none, 1 not a corpse, 2 a corpse), returned, state put, missile row (-1 none),")
    print("//   flags, way x, way y, velocity, life } a missile made, in order")
    for level in (1, 10, 20):
        for kind in (0, 1, 2):
            case(83, level, kind)


if __name__ == "__main__":
    main()
