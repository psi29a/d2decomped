"""A missile's pierce charges as game.exe makes it: FUN_0059f940 run natively.

    uv run python pierce_charges.py [cases] [seed] [--dump ../../tests/pierce_charges_cases.inc]

FUN_0059f940 (EAX the owner, the missile on the stack) runs from
FUN_0059fa30 for every missile. A case: the owner a player, the missile a
Pierce row (FUN_0046ace0 hooked to a record whose byte +4 is 4, the mask
at 0x6ce270), the owner's skill_pierce (stat 0xa6, FUN_00625480) and
item_pierce (0x9c, FUN_00625500), and its pierce_idx (0x148,
FUN_006253b0), the seed. FUN_00627260 records the missile's stat 0x148
(none set: 0). A line: skill_pierce, item_pierce, pierce_idx, charges.
tests/test_pierce_charges.cpp runs rules::pierce_charges on each.
"""
import random
import sys

import emu


def main():
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    dump = sys.argv[sys.argv.index("--dump") + 1] if "--dump" in sys.argv else None
    if dump: args.remove(dump)
    cases, seed = int(args[0]) if args else 2000, int(args[1]) if len(args) > 1 else 1
    rng = random.Random(seed)
    e = emu.Emu()
    owner, missile, record = e.alloc(0x100), e.alloc(0x100), e.alloc(0x1A4)
    e.w32(missile, 3)                                            # unit type 3: a missile
    e.mu.mem_write(record + 4, bytes((4,)))                      # the Pierce flag
    stats, charges = {}, []
    e.hook(0x46ACE0, lambda e: record, 0)                        # fastcall, ECX the class
    e.hook(0x625480, lambda e: stats[e.arg(1)] if e.arg(0) == owner else 0, 3)
    e.hook(0x625500, lambda e: stats[e.arg(1)] if e.arg(0) == owner else 0, 3)
    e.hook(0x6253B0, lambda e: stats[e.arg(1)] if e.arg(0) == owner else 0, 3)
    e.hook(0x627260, lambda e: charges.append(e.arg(2)) if (e.arg(0), e.arg(1)) == (missile, 0x148) else 0, 4)
    lines = []
    for _ in range(cases):
        skill, item = rng.choice((0, 0, rng.randint(1, 60), rng.randint(-20, 130))), rng.choice((0, 0, rng.randint(1, 50), rng.randint(-20, 130)))
        idx = rng.choice((rng.randrange(0, 200), rng.randrange(1 << 32)))
        stats.update({0xA6: skill, 0x9C: item, 0x148: idx})
        charges.clear()
        e.call(0x59F940, missile, regs={"eax": owner})
        lines.append(f"    {{ {skill}, {item}, {idx}u, {charges[0] if charges else 0} }},")
    out = open(dump, "w") if dump else sys.stdout
    print(f"// Stock game.exe 1.14d, FUN_0059f940; generated by tools/emu/pierce_charges.py {cases} {seed}.", file=out)
    print("// skill_pierce, item_pierce, pierce_idx (the seed), charges", file=out)
    print("\n".join(lines), file=out)


if __name__ == "__main__":
    main()
