"""A blocked path end walked back toward the start: FUN_00648120 in game.exe.

FUN_00649970 calls it for a path whose type has flag 0x1000 (PATHTYPEFLAGS
0x6eb690: types 0, 1 and 7, a player's) when FUN_0064d910 finds the end
blocked. It runs here on random starts, ends and walls with FUN_0064d910
answering from the case's walls; a player's (owner type 0) goes on into
FUN_00648050, the push-on. Each row is the case, FUN_00648120's return and
the end it left: tests/walk_back_cases.inc, which tests/test_walk_back.cpp
replays through rules::end_walk_back.

  uv run walk_back.py [cases] > ../../tests/walk_back_cases.inc
"""
import random
import sys

import emu


def main():
    cases = int(sys.argv[1]) if len(sys.argv) > 1 else 600
    rng = random.Random(0x648120)
    e = emu.Emu()
    walls, asked = set(), set()
    def collide(e):
        at = (e.arg(1) & 0xffff, e.arg(2) & 0xffff)
        asked.add(at)
        return int(at in walls)
    e.hook(0x64d910, collide, 5)
    print("// Stock game.exe 1.14d, FUN_00648120 (and FUN_00648050 for a player); generated by tools/emu/walk_back.py.")
    print("// start x, y, end x, y, player, the walls it asked about, then FUN_00648120's return and the end it left")
    mark = e.brk
    for _ in range(cases):
        e.brk = mark
        x, y = 1000, 1000
        spread = rng.choice((2, 4, 6, 12))
        to_x, to_y = x + rng.randint(-spread, spread), y + rng.randint(-spread, spread)
        player = rng.random() < 0.5
        walls.clear(); asked.clear()
        walls.add((to_x, to_y))
        density = rng.choice((0.1, 0.3, 0.6, 0.9))
        for wall_x in range(x - 18, x + 19):
            for wall_y in range(y - 18, y + 19):
                if rng.random() < density: walls.add((wall_x, wall_y))
        if rng.random() < 0.8: walls.discard((x, y))
        unit, path, ctx = e.alloc(0x100), e.alloc(0x200), e.alloc(0x40)
        e.w32(unit, 0 if player else 1); e.w32(unit + 0x2c, path); e.w32(path + 0x30, unit)
        e.w32(ctx, y << 16 | x); e.w32(ctx + 4, to_y << 16 | to_x); e.w32(ctx + 8, 1); e.w32(ctx + 0x30, path)
        ret = e.call(0x648120, regs={"eax": ctx})
        end = e.r32(ctx + 4)
        near = sorted((a - x, b - y) for a, b in walls & asked)
        rows = ", ".join(f"{{ {a}, {b} }}" for a, b in near)
        print(f"    {{ 0, 0, {to_x - x}, {to_y - y}, {int(player)}, {{ {rows} }}, {ret}, {(end & 0xffff) - x}, {(end >> 16) - y} }},")


if __name__ == "__main__":
    main()
