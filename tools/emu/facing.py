"""A walker's facing in game.exe: the aim's direction and the turn toward it.

FUN_0064fc60 (the aim) writes the unit vector through ECX and a 64-step
direction through EDX; FUN_0064fe40 hands that to FUN_006485f0 (a new goal,
path +0x65, its step +0x66 from DIFFDIRECTIONS 0x6eb548), and FUN_00648640
turns path +0x64 a step a frame. Prints tests/facing_cases.inc, which
tests/test_facing.cpp replays through rules::missile_aim, rules::aim_direction
and rules::Facing:

  uv run facing.py [cases] > ../../tests/facing_cases.inc
"""
import random
import sys

import emu


def s32(value):
    return value - (1 << 32) if value & 0x80000000 else value


def main():
    cases = int(sys.argv[1]) if len(sys.argv) > 1 else 400
    rng = random.Random(0x6485f0)
    e = emu.Emu()
    out = e.alloc(16)
    print("// Stock game.exe 1.14d; generated by tools/emu/facing.py.")
    print("// kAimCases: x, y, to_x, to_y (16.16 subtiles), then FUN_0064fc60's vector and direction.")
    print("inline constexpr AimCase kAimCases[] = {")
    for _ in range(cases):
        x = (1000 + rng.randint(-50, 50)) << 16 | rng.randint(0, 0xffff)
        y = (1000 + rng.randint(-50, 50)) << 16 | rng.randint(0, 0xffff)
        kind = rng.random()
        if kind < 0.1: to_x, to_y = x, y                                         # on it
        elif kind < 0.3:                                                         # a subtile's centre near
            to_x = ((x >> 16) + rng.randint(-3, 3)) << 16 | 0x8000
            to_y = ((y >> 16) + rng.randint(-3, 3)) << 16 | 0x8000
        elif kind < 0.4:                                                         # on an axis or a diagonal
            span = rng.randint(1, 0x400000)
            to_x = x + rng.choice((-span, 0, span)); to_y = y + rng.choice((-span, 0, span))
        else:
            to_x = x + rng.randint(-0x600000, 0x600000); to_y = y + rng.randint(-0x600000, 0x600000)
        e.call(0x64fc60, x, y, to_x, to_y, ecx=out, edx=out + 8)
        print(f"    {{ 0x{x:x}, 0x{y:x}, 0x{to_x:x}, 0x{to_y:x}, {s32(e.r32(out))}, {s32(e.r32(out + 4))}, {e.r32(out + 8) & 0xff} }},")
    print("};")
    unit_at, path_at = e.alloc(0x100), e.alloc(0x200)
    path = e.view("path", path_at)
    e.view("unit", unit_at).type = 1
    path.owner, path.flags = unit_at, 0                                         # a monster's path: it turns
    diff = [e.r32(0x6eb548 + 4 * i) & 0xff for i in range(64)]
    print("// kTurnCases: the facing's now and goal, then per frame a new goal (-1 none) and now / goal after the turn.")
    print("inline constexpr TurnCase kTurnCases[] = {")
    for _ in range(cases):
        now, goal = rng.randint(0, 63), rng.randint(0, 63)
        path.facing, path.facing_goal, path.turn_step = now, goal, diff[(goal - now) & 0x3f]
        frames = []
        for _ in range(12):
            new = rng.randint(0, 63) if rng.random() < 0.25 else -1
            if new >= 0:
                e.call(0x6485f0, ecx=path_at, edx=new)
            e.call(0x648640, path_at)
            frames.append((new, path.facing, path.facing_goal))
        steps = ", ".join(f"{{ {new}, {at}, {to} }}" for new, at, to in frames)
        print(f"    {{ {now}, {goal}, {{ {steps} }} }},")
    print("};")


if __name__ == "__main__":
    main()
