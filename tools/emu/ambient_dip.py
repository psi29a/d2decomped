"""The ambient's dip to black, a frame at a time (FUN_0046ae50, FUN_0046ad10).

    uv run python ambient_dip.py gen 300 1 > cases.tsv
    uv run python ambient_dip.py [--exe PATH] game cases.tsv > g.txt   # each case line + game.exe's lights
    ../../build/tests/test_ambient_dip cases.tsv | diff g.txt -
    uv run python ambient_dip.py inc g.txt > ../../tests/ambient_dip_cases.inc

Each case starts a dip as FUN_0046ae50 does (fastcall: ECX the fade in,
EDX the hold; the fade back, the level, force 0 on the stack), then runs
FUN_0046ad10 a frame at a time, as FUN_0046beb0 does while 0x7a742c is
set, and after each frame asks FUN_00474550 with flag 1 (FUN_00474610's
call) what the grid is filled with. All three run for real. A level here
is a number FUN_0061a1b0 (hooked) hands back as its id; FUN_00619d70
(hooked) gives a level 0x10000 + n the light n, white, and FUN_004646a0
(hooked) is the client's level: the dip's own until frame `change`, then
the next one (another fill, which ends the dip).

A case: `seq in hold back fill change other`. `game` prints the case
line, then `=` and the fill after each frame until the dip is off.
"""
import random
import sys

import emu

DIP_ON = 0x7A742C
GET_LEVEL_ID, LEVEL_LIGHT, ENV_RGB, ENV_INTENSITY, CLIENT_LEVEL = 0x61A1B0, 0x619D70, 0x61C0B0, 0x61C0E0, 0x4646A0
FILL, DIP_START, DIP_FRAME = 0x474550, 0x46AE50, 0x46AD10
LEVEL = 0x10000                                                   # a level whose light is its low bits


def gen(count, seed):
    rng = random.Random(seed)
    # Cloak of Shadows' (auralencalc ln34: 200, 25 a level) and the Cairn Stones' (40, 220, 40)
    fixed = [(5, length * 3 // 5, length * 2 // 5) for length in (200, 225, 250, 300, 500, 675)] + [(40, 220, 40)]
    for seq in range(count):
        if seq < len(fixed):
            fade_in, hold, back = fixed[seq]
        else:
            fade_in = rng.choice((1, 2, 3, 5, 7, 40, rng.randint(1, 60)))
            hold = rng.choice((0, 1, 2, 120, rng.randint(0, 80)))
            back = rng.choice((0, 1, 2, 5, 40, rng.randint(0, 60)))
        fill = rng.choice((0, 1, 40, 80, 120, 128, 140, 200, 255, rng.randint(0, 255)))
        total = fade_in + hold + back
        change = rng.randint(1, total + 1) if rng.random() < 0.2 else total + 10   # the frame the client's level changes
        other = rng.choice((fill, rng.randint(0, 255)))
        print(seq, fade_in, hold, back, fill, change, other)


def game(path, exe=None):
    e = emu.Emu(exe=exe)

    def put_bytes(e, addresses, values):
        """Write each value as one byte to its address (the hooks' out-parameters)."""
        for address, value in zip(addresses, values):
            e.mu.mem_write(address, bytes([value]))

    client = [LEVEL]
    e.hook(GET_LEVEL_ID, lambda e: e.arg(0), 1)
    e.hook(LEVEL_LIGHT, lambda e: put_bytes(e, [e.arg(i) for i in range(1, 5)], (e.arg(0) & 0xFF, 255, 255, 255)) or 0, 5)
    e.hook(ENV_RGB, lambda e: put_bytes(e, [e.arg(i) for i in range(1, 4)], (255, 255, 255)) or 0, 4)
    e.hook(ENV_INTENSITY, lambda e: 200, 1)
    e.hook(CLIENT_LEVEL, lambda e: client[0], 0)
    out = e.alloc(16)

    def fill(level):
        """FUN_00474550(level, &intensity, &red, &green, &blue, 1)"""
        e.call(FILL, out + 4, out + 8, out + 12, 1, ecx=level, edx=out)
        return e.s32(out)

    for line in open(path):
        seq, fade_in, hold, back, light, change, other = map(int, line.split())
        own, next_level = LEVEL + light, LEVEL + 0x100 + other
        client[0] = own
        e.call(DIP_START, back, own, 0, ecx=fade_in, edx=hold)
        seen = []
        for frame in range(fade_in + hold + back + 30):
            if not e.r32(DIP_ON):
                break
            if frame == change:
                client[0] = next_level
            e.call(DIP_FRAME)
            seen.append(fill(client[0]))
        else:
            sys.exit(f"ambient_dip: case {seq} never ended")
        print(seq, fade_in, hold, back, light, change, other, "=", *seen)


def inc(path):
    print("// Stock game.exe 1.14d, FUN_0046ae50 / FUN_0046ad10 / FUN_00474550;")
    print("// generated by tools/emu/ambient_dip.py (gen 300 1, game, inc).")
    print('// { "the case line", "the fill after each frame" }')
    for line in open(path):
        case, answers = line.split("=")
        print(f'    {{ "{case.strip()}", "{answers.strip()}" }},')


def main():
    args = sys.argv[1:]
    exe = None
    if "--exe" in args:
        at = args.index("--exe")
        exe = args[at + 1]
        del args[at:at + 2]
    if len(args) == 3 and args[0] == "gen":
        gen(int(args[1]), int(args[2]))
    elif len(args) == 2 and args[0] == "game":
        game(args[1], exe)
    elif len(args) == 2 and args[0] == "inc":
        inc(args[1])
    else:
        sys.exit(__doc__)


if __name__ == "__main__":
    main()
